"""NF-9: hash-locked dependencies, SHA-pinned Actions, checksummed downloads."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GITLEAKS_SHA256 = "551f6fc83ea457d62a0d98237cbad105af8d557003051f41f3e7ca7b3f2470eb"
CHECKOUT_SHA = "11d5960a326750d5838078e36cf38b85af677262"
SETUP_PYTHON_SHA = "a26af69be951a213d495a4c3e4e4022e16d87065"


def _lock_text(name: str) -> str:
    return (ROOT / name).read_text(encoding="utf-8")


def _requirement_blocks(text: str) -> list[str]:
    blocks: list[str] = []
    current: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            if current:
                blocks.append(" ".join(current))
                current = []
            continue
        current.append(stripped.rstrip("\\").strip())
    if current:
        blocks.append(" ".join(current))
    return [block for block in blocks if "==" in block or " @ " in block]


def test_requirement_locks_are_hash_pinned():
    for name in ("requirements.txt", "requirements-dev.txt", "requirements-presidio.txt"):
        text = _lock_text(name)
        assert "autogenerated by pip-compile" in text
        blocks = _requirement_blocks(text)
        assert blocks, name
        for block in blocks:
            assert "--hash=sha256:" in block, block[:120]


def test_presidio_lock_pins_the_engine_and_spacy_model():
    text = _lock_text("requirements-presidio.txt")
    assert "presidio-analyzer==2.2.362" in text
    assert "presidio-anonymizer==2.2.362" in text
    assert "spacy==3.8.16" in text
    assert "en_core_web_lg-3.8.0-py3-none-any.whl" in text
    assert "293e9547a655b25499198ab15a525b05b9407a75f10255e405e8c3854329ab63" in text


def test_direct_pins_match_pyproject():
    project = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    runtime = (ROOT / "requirements.in").read_text(encoding="utf-8")
    for pin in ("httpx==0.28.1", "mcp==1.30.0", "pydantic==2.14.1", "pyyaml==6.0.3", "uvicorn==0.54.0"):
        assert pin in project
        assert pin in runtime
        assert pin.split("==")[0] in _lock_text("requirements.txt")


def test_workflow_pins_actions_hashes_and_checksums():
    workflow = (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    assert f"actions/checkout@{CHECKOUT_SHA}" in workflow
    assert f"actions/setup-python@{SETUP_PYTHON_SHA}" in workflow
    assert not re.search(r"uses:\s+\S+@v\d+", workflow)
    assert "--require-hashes" in workflow
    assert "sha256sum -c -" in workflow
    assert GITLEAKS_SHA256 in workflow
    assert "cyclonedx-py environment --of JSON -o sbom.json" in workflow
    assert 'pytest -m "not native"' in workflow
    assert "pytest -m native" in workflow
    assert "PRM_REQUIRE_NATIVE" in workflow
